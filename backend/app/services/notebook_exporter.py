"""Notebook exporter: Converts experiment spec & provenance ledger into a standalone Jupyter Notebook (.ipynb).

Supports 1-click export for local Jupyter or Google Colab execution.
When no author repository exists, generates domain-specific model code
(TextCNN for NLP+CNN, ResNet for CV, Bi-LSTM for NLP+RNN, etc.)
based on paper methodology detection.
"""
import json
from typing import Any
from pathlib import Path

from . import architecture_builder, model_templates


def _param_val(params: dict, key: str, default: Any = None) -> Any:
    """Safely extract a scalar value from the params dict (which may have nested dicts from paper_analyzer)."""
    v = params.get(key)
    if isinstance(v, dict):
        return v.get("value", default)
    return v if v is not None else default


def generate_notebook(
    spec: dict[str, Any],
    project_name: str = "CrisisGrid Reproduction",
    repo_path: Path | str | None = None,
    methodology: dict[str, Any] | None = None,
    is_paper_only: bool | None = None,
    model_code: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Return a valid Jupyter Notebook JSON dict (.ipynb format v4) with executable model code.

    Args:
        spec: Experiment spec with 'claim' and 'params'.
        project_name: Human-readable project name for the notebook title.
        repo_path: Path to the cloned repository (if available).
        methodology: Output of paper_analyzer.detect_methodology (architecture + domain).
        is_paper_only: Force paper-only mode if True, otherwise infer from repo_path.
        model_code: Precomputed architecture_builder result; skips generation when given.
    """
    claim = spec.get("claim", {})
    params = spec.get("params", {})
    claim_metric = (claim.get("metric") or "accuracy").upper()
    claim_val = claim.get("value")
    claim_quote = claim.get("quote") or ""
    claim_page = claim.get("page") or 1

    arch = (methodology or {}).get("architecture", "mlp")
    domain = (methodology or {}).get("domain", "tabular")
    arch_details = (methodology or {}).get("architecture_details", [])
    domain_details = (methodology or {}).get("domain_details", [])

    # Determine if this is paper-only mode
    if is_paper_only is None:
        if repo_path:
            rp = Path(repo_path)
            is_paper_only = not (rp.exists() and (rp / "train.py").exists())
        else:
            is_paper_only = True

    cells = []

    # ── Cell 1: Markdown Title & Metadata ───────────────────────────────────
    mode_badge = "📄 Paper-Only Autonomous Reconstruction" if is_paper_only else "📦 Repository-Based Reproduction"
    arch_label = arch.upper().replace("_", " ")
    domain_label = domain.upper()

    title_md = f"""# 🔬 {project_name} — Research Reproducibility Notebook
Generated by **CrisisGrid.AI** • *AI interprets · code measures*

| Property | Value |
| :--- | :--- |
| **Target Metric** | `{claim_metric}` |
| **Published Claim** | `{claim_val}{'%' if claim.get('percent') else ''}` (Page {claim_page}) |
| **Verbatim Quote** | *"{claim_quote}"* |
| **Detected Architecture** | `{arch_label}` ({', '.join(arch_details[:3]) if arch_details else 'generic'}) |
| **Detected Domain** | `{domain_label}` ({', '.join(domain_details[:2]) if domain_details else 'unknown'}) |
| **Mode** | {mode_badge} |

---
"""
    cells.append({
        "cell_type": "markdown",
        "metadata": {},
        "source": title_md.splitlines(keepends=True)
    })

    # ── Cell 2: Colab/Jupyter Setup & Seed Fixation ─────────────────────────
    # Determine if PyTorch is needed
    needs_torch = is_paper_only and arch in (
        "cnn", "lstm", "rnn", "gru", "transformer", "bert", "gpt",
        "resnet", "vgg", "gan", "autoencoder"
    )

    setup_lines = ["# 1. Environment & Dependency Setup\n"]
    if needs_torch:
        setup_lines.append("# Install PyTorch if running in Google Colab\n")
        setup_lines.append("try:\n")
        setup_lines.append("    import torch\n")
        setup_lines.append("except ImportError:\n")
        setup_lines.append("    import subprocess, sys\n")
        setup_lines.append("    subprocess.check_call([sys.executable, '-m', 'pip', 'install', 'torch', '--quiet'])\n")
        setup_lines.append("    import torch\n")
        setup_lines.append("\n")

    setup_lines.extend([
        "import os\n",
        "import sys\n",
        "import json\n",
        "import numpy as np\n",
        "\n",
        "# Set random seeds for deterministic execution\n",
    ])

    seed_val = _param_val(params, "seed", 42)
    setup_lines.append(f"DEFAULT_SEED = {seed_val}\n")
    setup_lines.append("np.random.seed(DEFAULT_SEED)\n")

    if needs_torch:
        setup_lines.extend([
            "torch.manual_seed(DEFAULT_SEED)\n",
            "if torch.cuda.is_available():\n",
            "    torch.cuda.manual_seed_all(DEFAULT_SEED)\n",
        ])

    setup_lines.extend([
        "\n",
        'print(f"Environment initialized. Seed={DEFAULT_SEED}")\n',
    ])

    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": setup_lines
    })

    # ── Cell 3: Reconstructed Hyperparameters ───────────────────────────────
    params_lines = ["# 2. Reconstructed Hyperparameters from Paper\n", "PARAMS = {\n"]
    for k, v in params.items():
        if k.startswith("_"):
            continue
        if isinstance(v, dict):
            val = v.get("value")
            src = v.get("source", "inferred")
            page = v.get("page")
            quote = v.get("quote", "")
            page_note = f" (Page {page})" if page else ""
            quote_note = f': "{quote}"' if quote else ""
            params_lines.append(f'    "{k}": {repr(val)},  # {src}{page_note}{quote_note}\n')
        else:
            params_lines.append(f'    "{k}": {repr(v)},\n')
    params_lines.append("}\n\n")
    params_lines.append('print("Reconstructed Hyperparameters:")\n')
    params_lines.append('for k, v in PARAMS.items():\n')
    params_lines.append('    print(f"  {k}: {v}")\n')

    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": params_lines
    })

    # ── Cell 4: Model Definition & Training Pipeline ────────────────────────
    model_code_cell = None

    if not is_paper_only:
        # Embed actual train.py from the cloned repository
        try:
            rp = Path(repo_path)  # type: ignore[arg-type]
            code_text = (rp / "train.py").read_text()
            model_code_cell = f"""# 3. Model Definition & Training Pipeline (From Author Repository)
# Source: {repo_path}/train.py
# This is the author's actual model code, AST-scanned by CrisisGrid.

{code_text}
"""
        except Exception:
            pass

    if not model_code_cell:
        # Paper-Only Mode: Use Gemini Architecture Builder with Template fallback
        arch_res = model_code or architecture_builder.build_model_code_for_notebook(
            spec=spec,
            methodology=methodology,
            project_name=project_name
        )
        code_body = arch_res["code"]
        header = f"""# 3. Model Architecture & Training Pipeline
# Model Architecture: {arch_res['architecture_name']} ({arch_res['framework'].upper()})
# Generator Engine: {arch_res['source'].upper()} Mode
# Summary: {arch_res['notes']}

"""
        if not code_body.startswith("# 3."):
            model_code_cell = header + code_body
        else:
            model_code_cell = code_body

    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": model_code_cell.splitlines(keepends=True)
    })

    # ── Cell 5: Empirical Verification ──────────────────────────────────────
    exec_code = f"""# 4. Empirical Verification Against Published Claim
# Target: {claim_metric} = {claim_val}{'%' if claim.get('percent') else ''}

PUBLISHED_CLAIM = {claim_val if claim_val is not None else 'None'}
TOLERANCE_PP = 2.0  # ±2.0 percentage points tolerance

def verify_reproduction(measured_metric):
    if PUBLISHED_CLAIM is None:
        print("No ground truth claim specified in paper.")
        return
    delta_pp = measured_metric - PUBLISHED_CLAIM
    within_tolerance = abs(delta_pp) <= TOLERANCE_PP

    print("=" * 60)
    print("    CRISISGRID EMPIRICAL REPRODUCIBILITY AUDIT")
    print("=" * 60)
    print(f"  Published Claim  : {{PUBLISHED_CLAIM:.2f}}%")
    print(f"  Empirical Output : {{measured_metric:.2f}}%")
    print(f"  Metric Delta     : {{delta_pp:+.2f}} pp")
    print(f"  Tolerance Window : ±{{TOLERANCE_PP}} pp")
    print(f"  Verdict          : {{'✅ REPRODUCED' if within_tolerance else '❌ NOT REPRODUCED'}}")
    print("=" * 60)

# Run verification
try:
    verify_reproduction(empirical_value)
except NameError:
    print("⚠️  empirical_value not defined — run the training cell above first.")
"""
    cells.append({
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": exec_code.splitlines(keepends=True)
    })

    # ── Cell 6: Evidence Provenance Ledger ──────────────────────────────────
    ledger_md = """### 📋 Evidence Provenance Ledger
Every parameter in this notebook is anchored to exact PDF page quotes and AST-scanned source lines.

| Parameter | Value | Source | Page | Quote | Verified |
| :--- | :--- | :--- | :--- | :--- | :--- |
"""
    for k, v in params.items():
        if k.startswith("_"):
            continue
        if isinstance(v, dict):
            val = v.get("value", "None")
            src = v.get("source", "inferred")
            page = v.get("page", "—")
            quote = v.get("quote", "—") or "—"
            ver = "✅" if v.get("verified") else "—"
            ledger_md += f"| `{k}` | `{val}` | {src} | {page} | *{quote[:60]}* | {ver} |\n"

    if is_paper_only:
        ledger_md += f"\n> **Note**: This notebook was autonomously synthesized by CrisisGrid (Paper-Only Mode).\n"
        ledger_md += f"> Detected architecture: **{arch_label}** • Domain: **{domain_label}**\n"

    cells.append({
        "cell_type": "markdown",
        "metadata": {},
        "source": ledger_md.splitlines(keepends=True)
    })

    return {
        "cells": cells,
        "metadata": {
            "language_info": {
                "name": "python"
            },
            "orig_nbformat": 4,
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3"
            }
        },
        "nbformat": 4,
        "nbformat_minor": 2
    }
