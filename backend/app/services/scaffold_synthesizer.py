def _generate_mlp_script(lr: float, bs: int, epochs: int, seed: int) -> str:
    return f'''#!/usr/bin/env python3
"""Autonomously synthesized benchmark script generated by CrisisGrid.AI.
Reconstructed from research paper methodology specifications.
"""
import argparse
import json
import os
import sys
import numpy as np
from sklearn.datasets import make_classification
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import accuracy_score, f1_score, log_loss

def parse_args():
    parser = argparse.ArgumentParser(description="Paper-Only Reconstructed Workflow")
    parser.add_argument("--lr", type=float, default={lr}, help="Learning rate (extracted from paper)")
    parser.add_argument("--batch_size", type=int, default={bs}, help="Batch size (extracted from paper)")
    parser.add_argument("--epochs", type=int, default={epochs}, help="Number of training epochs")
    parser.add_argument("--seed", type=int, default={seed}, help="Random seed for deterministic runs")
    parser.add_argument("--out", type=str, required=True, help="Output JSON metrics path")
    return parser.parse_args()

def main():
    args = parse_args()
    print(f"[*] Running reconstructed experiment with seed={{args.seed}}, lr={{args.lr}}, bs={{args.batch_size}}")

    # Set deterministic random seed
    np.random.seed(args.seed)

    # Deterministic dataset synthesis aligned with target problem complexity
    X, y = make_classification(
        n_samples=1200,
        n_features=20,
        n_informative=14,
        n_classes=2,
        random_state=args.seed
    )

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=args.seed
    )

    # Multi-layer Perceptron representing paper methodology
    clf = MLPClassifier(
        hidden_layer_sizes=(64, 32),
        learning_rate_init=args.lr,
        batch_size=min(args.batch_size, len(X_train)),
        max_iter=args.epochs * 20,
        random_state=args.seed
    )

    clf.fit(X_train, y_train)
    y_pred = clf.predict(X_test)
    y_prob = clf.predict_proba(X_test)

    acc = float(accuracy_score(y_test, y_pred)) * 100.0
    f1 = float(f1_score(y_test, y_pred, average="weighted")) * 100.0
    loss = float(log_loss(y_test, y_prob))

    print(f"[*] Results: Accuracy={{acc:.2f}}%, F1={{f1:.2f}}%, Loss={{loss:.4f}}")

    metrics = {{
        "accuracy": round(acc, 2),
        "f1": round(f1, 2),
        "loss": round(loss, 4),
        "epochs": args.epochs,
        "seed": args.seed,
    }}

    # Write output metrics JSON for CrisisGrid verifier
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        json.dump(metrics, f, indent=2)

    print(f"[✓] Metrics written to {{args.out}}")

if __name__ == "__main__":
    main()
'''
